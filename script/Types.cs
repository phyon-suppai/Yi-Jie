/// <summary>三种烦恼:疑 / 焦 / 孤</summary>
public enum WorryType
{
	Doubt,     // 疑(绿)——原地打转、不主动追人
	Pressure,  // 焦(红)——过载,缓慢移动
	Loneliness // 孤(蓝)——半透明,会贴到身后
}

/// <summary>三种武器:行动(绿) / 表达(蓝) / 接受(红)</summary>
public enum WeaponType
{
	Act,     // 行动(绿)——直线单体
	Express, // 表达(蓝)——回旋群体
	Accept   // 接受(红)——范围瞬发
}
